package com.projectapex.dto.request;

import jakarta.validation.constraints.NotBlank;

public class CommitBookingRequest {
    @NotBlank(message = "Court ID is required")
    private String courtId;

    @NotBlank(message = "Date is required")
    private String date;

    @NotBlank(message = "Slot time is required")
    private String slot;

    @NotBlank(message = "Razorpay Order ID is required")
    private String razorpayOrderId;

    @NotBlank(message = "Razorpay Payment ID is required")
    private String razorpayPaymentId;

    @NotBlank(message = "Razorpay Signature is required")
    private String razorpaySignature;

    private String paymentMethod; // "UPI", "Card", "NetBanking"

    public CommitBookingRequest() {}

    public String getCourtId() { return courtId; }
    public void setCourtId(String courtId) { this.courtId = courtId; }

    public String getDate() { return date; }
    public void setDate(String date) { this.date = date; }

    public String getSlot() { return slot; }
    public void setSlot(String slot) { this.slot = slot; }

    public String getRazorpayOrderId() { return razorpayOrderId; }
    public void setRazorpayOrderId(String razorpayOrderId) { this.razorpayOrderId = razorpayOrderId; }

    public String getRazorpayPaymentId() { return razorpayPaymentId; }
    public void setRazorpayPaymentId(String razorpayPaymentId) { this.razorpayPaymentId = razorpayPaymentId; }

    public String getRazorpaySignature() { return razorpaySignature; }
    public void setRazorpaySignature(String razorpaySignature) { this.razorpaySignature = razorpaySignature; }

    public String getPaymentMethod() { return paymentMethod != null ? paymentMethod : "UPI"; }
    public void setPaymentMethod(String paymentMethod) { this.paymentMethod = paymentMethod; }
}
